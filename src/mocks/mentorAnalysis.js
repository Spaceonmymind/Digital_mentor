export function mockMentorAnalysis(onProgress) {
  let index = 0;
  const stepDelay = 1200;

  return new Promise((resolve) => {
    const tick = () => {
      onProgress(index);
      index += 1;

      if (index < analysisSteps.length) {
        window.setTimeout(tick, stepDelay);
        return;
      }

      window.setTimeout(() => resolve(mentorResult), stepDelay);
    };

    tick();
  });
}
